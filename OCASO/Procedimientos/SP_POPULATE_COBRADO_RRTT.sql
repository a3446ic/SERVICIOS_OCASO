CREATE or replace PROCEDURE EXT.SP_POPULATE_COBRADO_RRTT (IN i_file_name varchar(120), IN i_id_proceso BIGINT, INOUT i_log_count INT)
LANGUAGE SQLSCRIPT 
SQL SECURITY INVOKER 
DEFAULT SCHEMA EXT AS
 
/*---------------------------------------------------------------------
    | Author: Jorge Gracia Estaun
    | Company: Inycom
    | Initial Version Date: 06-Febrero-2025
    |----------------------------------------------------------------------
    | Procedure Purpose: Procedimiento que se ejecuta una vez que entra un fichero de COBRADO DE RRTT e inserta los datos en las tablas finales de 
    |						RECIBOS, POLIZAS, GARANTIAS RECIBOS, ASEGURADOS y GARANTIAS DE ASEGURADOS  + TRANSACCIONES
    |		COBRADO ETERNA RRTT	RECIAFLFTP163302P
	|		COBRADO OCASO RRTT	RECIOFLFTP163202P
	|	
	|
	| Version: 0.1	JGE 20250206		Initial Version.
	| Version: 0.2 	TGV 20260521		Por peticion de Comercial (JGF) se deben generar 72+ para todas las comisiones anticipadas por lo que quitamos los filtros de ASISA
    |
	|
    -----------------------------------------------------------------------
*/
 
BEGIN
	USING SQLSCRIPT_STRING AS LIBRARY;
	
	DECLARE proc_name VARCHAR2(50) := ::CURRENT_OBJECT_SCHEMA ||'.'|| ::CURRENT_OBJECT_NAME;
	DECLARE v_version VARCHAR2(10) := '0.2';
	DECLARE v_idtenant VARCHAR(50) := EXT.LIB_GLOBAL:getTenantID();
	DECLARE v_permisos_log VARCHAR(50) := EXT.LIB_GLOBAL:GET_PERMISOS_LOG();
	DECLARE v_eot DATE := EXT.LIB_CONSTANTES:v_eot;
	DECLARE v_tenantid VARCHAR(4) := '';
	
	DECLARE v_num_rows INTEGER := 0;
	
	DECLARE CONST_STAGE_STATUS_OK INT := EXT.LIB_CONSTANTES:CONST_STAGE_STATUS_OK;					--1
	DECLARE CONST_GENERA_TRX_STATUS_OK INT := EXT.LIB_CONSTANTES:CONST_GENERA_TRX_STATUS_OK;		--9
    DECLARE CONST_GENERA_TRX_STATUS_ERROR INT := EXT.LIB_CONSTANTES:CONST_GENERA_TRX_STATUS_ERROR;	--5
    DECLARE CONST_POPULATE_STATUS_OK INT := EXT.LIB_CONSTANTES:CONST_POPULATE_STATUS_OK;			--2
	DECLARE CONST_POPULATE_STATUS_ERROR INT := EXT.LIB_CONSTANTES:CONST_POPULATE_STATUS_ERROR;		--4
	DECLARE CONST_TIPO_REC_ANUL_K5 VARCHAR(2) := EXT.LIB_CONSTANTES:CONST_TIPO_REC_ANUL_K5;
	
	DECLARE CONST_RECIBOS_ESPECIFICOS_10 VARCHAR(2) := EXT.LIB_CONSTANTES:CONST_RECIBOS_ESPECIFICOS_10;
	DECLARE CONST_RECIBOS_ESPECIFICOS_20 VARCHAR(2) := EXT.LIB_CONSTANTES:CONST_RECIBOS_ESPECIFICOS_20;
	DECLARE CONST_RECIBOS_ESPECIFICOS_71 VARCHAR(2) := EXT.LIB_CONSTANTES:CONST_RECIBOS_ESPECIFICOS_71;
	DECLARE CONST_RECIBOS_ESPECIFICOS_72 VARCHAR(2) := EXT.LIB_CONSTANTES:CONST_RECIBOS_ESPECIFICOS_72;
	DECLARE CONST_RECIBOS_ESPECIFICOS_16 VARCHAR(2) := EXT.LIB_CONSTANTES:CONST_RECIBOS_ESPECIFICOS_16;
	DECLARE CONST_RECIBO_EXTORNO VARCHAR2(6) := EXT.LIB_CONSTANTES:CONST_RECIBO_EXTORNO;
	DECLARE CONST_COD_SUPLEMENTO_10 INT := EXT.LIB_CONSTANTES:CONST_COD_SUPLEMENTO_100;
	DECLARE CONST_MOTIVO_ALTA_DE  VARCHAR(2) := EXT.LIB_CONSTANTES:CONST_MOTIVO_ALTA_DE;
	DECLARE CONST_COD_SUPLEMENTO_DEFECTO INT := EXT.LIB_CONSTANTES:CONST_COD_SUPLEMENTO_DEFECTO;
	DECLARE CONST_RECIBOS_ESPECIFICOS_66 VARCHAR2(2) := EXT.LIB_CONSTANTES:CONST_RECIBOS_ESPECIFICOS_66;
	DECLARE CONST_COD_SUPLEMENTO_DESDOBLES INT := EXT.LIB_CONSTANTES:CONST_COD_SUPLEMENTO_DESDOBLES;
	DECLARE CONST_NO_ENCONTRADO VARCHAR(20) := EXT.LIB_CONSTANTES:CONST_NO_ENCONTRADO; 
	DECLARE CONST_RECIBO_PENDIENTE VARCHAR(6) := EXT.LIB_CONSTANTES:CONST_RECIBO_PENDIENTE;
	DECLARE CONST_RECIBO_ANULADO VARCHAR(6) := EXT.LIB_CONSTANTES:CONST_RECIBO_ANULADO;
	DECLARE CONST_RECIBO_EMITIDO VARCHAR(6) := EXT.LIB_CONSTANTES:CONST_RECIBO_EMITIDO;
	DECLARE CONST_RECIBO_COBRADO VARCHAR(6) := EXT.LIB_CONSTANTES:CONST_RECIBO_COBRADO;
	DECLARE CONST_S VARCHAR(1) := EXT.LIB_CONSTANTES:CONST_S;

	DECLARE CONST_TIPO_EURO VARCHAR(255) := EXT.LIB_CONSTANTES:CONST_TIPO_EURO;
	DECLARE CONST_TIPO_PERCENTAGE VARCHAR(255) := EXT.LIB_CONSTANTES:CONST_TIPO_PERCENTAGE;
	
	DECLARE v_fecha_compensacion DATE;
	DECLARE v_status INTEGER := 0;
	DECLARE v_vueltas INTEGER := 1;
	DECLARE v_existe_tabla INTEGER := 0;
	
	
	DECLARE EXIT HANDLER FOR SQLEXCEPTION
		BEGIN
		
			ROLLBACK;
			
			CALL EXT.LIB_GLOBAL:WRITE_LOG (v_permisos_log, proc_name , 'Error en procedimiento principal ' || proc_name || ' - SQL_ERROR_MESSAGE: ' || IFNULL(::SQL_ERROR_MESSAGE,'')
																												|| '. SQL_ERROR_CODE: ' || ::SQL_ERROR_CODE, i_log_count, i_id_proceso, 'error');
			--v_hayError := 1;
			v_num_rows := 0;
			
			--Se obtiene la cuenta del fichero
			SELECT COUNT(*) INTO v_num_rows
			FROM EXT.STAGE_RECIBOS
			WHERE FILE_NAME = :i_file_name
				AND ESTADO = :CONST_STAGE_STATUS_OK;
			
			--Se actualizan los campos de la in_batch_control para indicar el error
			UPDATE EXT.IN_BATCH_CONTROL
			SET REJECTED_ROWS = :v_num_rows,
				STATUS = :CONST_GENERA_TRX_STATUS_ERROR,
				END_DATE = CURRENT_TIMESTAMP
			WHERE FILE_NAME = :i_file_name
				AND ID_PROCESO = :i_id_proceso;
			
			--Se actualizan los registros de STAGE_RECIBOS con estado err�neo
			UPDATE EXT.STAGE_RECIBOS
				SET ESTADO = :CONST_POPULATE_STATUS_ERROR,
				FECHA_MODIFICACION = CURRENT_TIMESTAMP
			WHERE FILE_NAME = :i_file_name
				AND ESTADO = :CONST_STAGE_STATUS_OK;	
			
			COMMIT;

			--Captura el error y lo env�a a xDL
			RESIGNAL;
		END;

	BEGIN
		
		CALL LIB_GLOBAL:WRITE_LOG (v_permisos_log, proc_name, 'Version: ' || v_version || ' - Procedure starting for ' || i_file_name, i_log_count, i_id_proceso, 'info');
		
		--Se comprueba estado del fichero
		SELECT STATUS INTO v_status FROM EXT.IN_BATCH_CONTROL WHERE FILE_NAME = :i_file_name ORDER BY START_DATE DESC LIMIT 1;
		
		IF (v_status <> :CONST_STAGE_STATUS_OK) THEN
			SIGNAL SQL_ERROR_CODE 10001
	    	SET MESSAGE_TEXT = 'Estado inv�lido: ' || :v_status;
	    ELSE 
	    	CALL LIB_GLOBAL:WRITE_LOG (v_permisos_log, proc_name, 'Estado IN_BATCH_CONTROL correcto' , i_log_count, i_id_proceso, 'info');
		END IF;
		
		SELECT DISTINCT TENANTID INTO v_tenantid FROM TCMP.CS_TENANT;
		
		CREATE LOCAL TEMPORARY TABLE #TBL_STAGE (
		    IDENTIFICADOR BIGINT,
		    FILE_NAME VARCHAR(255),
		    ESTADO INTEGER,
		    FECHA_MODIFICACION TIMESTAMP,
		    RAMO VARCHAR(255),
		    CODIGO_POLIZA VARCHAR(255),
		    MOTIVO_ALTA VARCHAR(255),
		    FECHA_EFECTO_POLIZA DATE,
		    FECHA_EMISION_POLIZA DATE,
		    FECHA_CESION_POLIZA DATE,
		    MOTIVO_BAJA VARCHAR(255),
		    FECHA_BAJA DATE,
		    FECHA_EFECTO_SUPLEMENTO DATE,
		    FECHA_VENCIMIENTO DATE,
		    FECHA_REHABILITACION DATE,
		    FORMA_PAGO VARCHAR(255),
		    TIPO_CAMPANIA VARCHAR(255),
		    CODIGO_AGENTE_ORIGINAL VARCHAR(255),
		    CODIGO_UNICO_AGENTE VARCHAR(255),
		    INSPECTOR VARCHAR(255),
		    OFICINA_COBRADORA VARCHAR(255),
		    OFICINA_GESTORA VARCHAR(255),
		    SEGUNDA_RESIDENCIA VARCHAR(255),
		    TARIFA VARCHAR(255),
		    ZONA VARCHAR(255),
		    CLAVE_RIESGO VARCHAR(255),
		    CODIGO_SUPLEMENTO VARCHAR(255),
		    DISTRITO_COBRO VARCHAR(255),
		    MODALIDAD VARCHAR(255),
		    DURACION VARCHAR(255),
		    IND_COMI_CALCULADA DECIMAL(25,4),
		    IND_POR_CALCULADO DECIMAL(25,4),
		    POR_COMI_CALCULADA DECIMAL(25,4),
		    IMPORTE_COMISION DECIMAL(25,4),
		    CLAUSULA VARCHAR(255),
		    AUMENTO_CAPITALES_GAR VARCHAR(255),
		    SUSTITUCION_INCENDIOS VARCHAR(255),
		    CODIGO_SINIESTRO VARCHAR(255),
		    EXCLUIDO_COMISIONES VARCHAR(255),
		    TRASPASADA VARCHAR(255),
		    INCRE_PRIMA_ANUAL DECIMAL(25,4),
		    DTO_IMPT_SINIESTRALIDAD DECIMAL(25,4),
		    DTO_POR_PRIORITARIO DECIMAL(25,4),
		    RIESGO VARCHAR(255),
		    COLECTIVO VARCHAR(255),
		    AUTOLIQUIDA VARCHAR(255),
		    KILOMETROS VARCHAR(255),
		    PRIMER_RECIBO VARCHAR(255),
		    CODIGO_RECIBO VARCHAR(255),
		    PERMANENCIA VARCHAR(255),
		    TIPO_RECIBO VARCHAR(255),
		    ESTADO_RECIBO VARCHAR(255),
		    FECHA_COBRO DATE,
		    FECHA_EFECTO_RECIBO DATE,
		    FECHA_VENCIMIENTO_RECIBO DATE,
		    TIPO_MOVIMIENTO VARCHAR(255),
		    PORC_DESTO_SOBREPC DECIMAL(25,4),
		    VALOR_POLIZA VARCHAR(255),
		    MARCA_RECUPERADO VARCHAR(255),
		    PRODUCTO_CONTABLE VARCHAR(255),
		    FECHA_ALTA_GAR_POL DATE,
		    FECHA_BAJA_GAR_POL DATE,
		    PRIMA_NETA_RECIBO DECIMAL(25,4),
		    PRIMA_BRUTA_RECIBO DECIMAL(25,4),
		    RECARGO VARCHAR(255),
		    PORCENTAJE_BONIFICACION DECIMAL(25,4),
		    POLIZA_CON_AGENTE VARCHAR(255),
		    MOVILIDAD VARCHAR(255),
		    PRIMA_UNICA VARCHAR(255),
		    NUM_ORDEN_MOVIMIENTO INTEGER,
		    FECHA_EMISION_REC DATE,
		    CARGO_COMPENSACION DATE,
		    ZONA_EXPLOTACION VARCHAR(255),
		    CODIGO_AGENTE_ZONA VARCHAR(255),
		    ORDERID VARCHAR(40),
		    SUBLINENUMBER DECIMAL(38,0),
		    LINENUMBER BIGINT,
		    ROW_NUMBER_RECIBOS INT
		);
		
		--Guardamos en una variable tabla informaci�n sobre jerarqu�a
		TBL_GEN_CODIGOS_AGENTE = SELECT * FROM EXT.VW_CODIGOS_DE_AGENTE VW
								WHERE 1=1
									AND VW.CODIGO_OCASO <> '0' 
									AND VW.CODIGO_OCASO <> '000000000' 
									AND VW.CODIGO_OCASO <> '0000000000'
								;
								
		v_num_rows = RECORD_COUNT(:TBL_GEN_CODIGOS_AGENTE);
		CALL LIB_GLOBAL:WRITE_LOG (v_permisos_log, proc_name, 'tabla agentes creada. Filas: ' || v_num_rows || ' filas' , i_log_count, i_id_proceso, 'info');
		
		--JGE 20250904 dividir todo lo que se pueda dividir en otras consultas para que no se queje el tio de sap
		--montar tabla con registros stage ok, agregar orderid, sublinenumber
		TBL_STAGE_0 = (
			SELECT 
				IDENTIFICADOR
				,FILE_NAME
				,ESTADO
				,FECHA_MODIFICACION
				,RAMO
				,CODIGO_POLIZA
				,MOTIVO_ALTA
				,FECHA_EFECTO_POLIZA
				,FECHA_EMISION_POLIZA
				,FECHA_CESION_POLIZA
				,MOTIVO_BAJA
				,FECHA_BAJA
				,FECHA_EFECTO_SUPLEMENTO
				,FECHA_VENCIMIENTO
				,FECHA_REHABILITACION
				,FORMA_PAGO
				,TIPO_CAMPANIA
				,CODIGO_AGENTE_ORIGINAL
				,CODIGO_UNICO_AGENTE
				,INSPECTOR
				,OFICINA_COBRADORA
				,OFICINA_GESTORA
				,SEGUNDA_RESIDENCIA
				,TARIFA
				,ZONA
				,CLAVE_RIESGO
				,(
					CASE 
					    WHEN PERMANENCIA = :CONST_RECIBOS_ESPECIFICOS_66
					         AND CODIGO_SUPLEMENTO = :CONST_COD_SUPLEMENTO_DEFECTO
					    THEN CONST_COD_SUPLEMENTO_DESDOBLES
					    WHEN PERMANENCIA = :CONST_RECIBOS_ESPECIFICOS_10
					    THEN CONST_COD_SUPLEMENTO_10
					    ELSE TO_INTEGER(COALESCE(CODIGO_SUPLEMENTO, :CONST_COD_SUPLEMENTO_DEFECTO))
					END	
				)AS CODIGO_SUPLEMENTO
				,DISTRITO_COBRO
				,MODALIDAD
				,DURACION
				,SUBSTR(IND_COMI_CALCULADA,1,1) AS IND_COMI_CALCULADA
				,SUBSTR(IND_POR_CALCULADO,1,1) AS IND_POR_CALCULADO
				,POR_COMI_CALCULADA
				,IMPORTE_COMISION
				,CLAUSULA
				,AUMENTO_CAPITALES_GAR
				,SUSTITUCION_INCENDIOS
				,CODIGO_SINIESTRO
				,EXCLUIDO_COMISIONES
				,TRASPASADA
				,INCRE_PRIMA_ANUAL
				,DTO_IMPT_SINIESTRALIDAD
				,DTO_POR_PRIORITARIO
				,RIESGO
				,COLECTIVO
				,AUTOLIQUIDA
				,KILOMETROS
				,PRIMER_RECIBO
				,CODIGO_RECIBO
				,(
					CASE WHEN MOTIVO_ALTA = :CONST_MOTIVO_ALTA_DE
				     AND PERMANENCIA = :CONST_RECIBOS_ESPECIFICOS_71
					    THEN 
					        CASE 
					            WHEN (
					                SELECT COALESCE(SUM(R.ASEGURADOS_NETOS), 0)
					                FROM EXT.RECIBOS R
					                WHERE R.CODIGO_POLIZA     = TBL.CODIGO_POLIZA
					                  AND R.CODIGO_RECIBO     = TBL.CODIGO_RECIBO
					                  AND R.CODIGO_SUPLEMENTO = COALESCE(TBL.CODIGO_SUPLEMENTO, :CONST_COD_SUPLEMENTO_DEFECTO)
					            ) = 0
					            THEN CONST_RECIBOS_ESPECIFICOS_66
					            ELSE PERMANENCIA
					        END
					    ELSE PERMANENCIA
					END
				)AS PERMANENCIA
				,TIPO_RECIBO
				,ESTADO_RECIBO
				,FECHA_COBRO 
				,FECHA_EFECTO_RECIBO
				,FECHA_VENCIMIENTO_RECIBO
				,TIPO_MOVIMIENTO
				,PORC_DESTO_SOBREPC
				,VALOR_POLIZA
				,MARCA_RECUPERADO
				,PRODUCTO_CONTABLE
				,FECHA_ALTA_GAR_POL
				,FECHA_BAJA_GAR_POL
				,PRIMA_NETA_RECIBO
				,PRIMA_BRUTA_RECIBO
				,RECARGO
				,PORCENTAJE_BONIFICACION
				,POLIZA_CON_AGENTE
				,MOVILIDAD
				,PRIMA_UNICA
				,NUM_ORDEN_MOVIMIENTO
				,FECHA_EMISION_REC
				,CARGO_COMPENSACION
				,ZONA_EXPLOTACION
				,CODIGO_AGENTE_ZONA
				--ORDERID
				,CASE 
			        WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			             AND UPPER(TIPO_RECIBO) = :CONST_TIPO_REC_ANUL_K5
			        THEN SUBSTR(PRODUCTO_CONTABLE || SUBSTR(CODIGO_POLIZA,8), 1, 23) || ' ' ||
			             (CASE WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			                   THEN OFICINA_COBRADORA ELSE OFICINA_GESTORA END) || CODIGO_RECIBO || '1'
			        
			        WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			             AND UPPER(ESTADO_RECIBO) = :CONST_RECIBO_EXTORNO
			        THEN SUBSTR(PRODUCTO_CONTABLE || SUBSTR(CODIGO_POLIZA,8), 1, 23) || ' ' ||
			             (CASE WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			                   THEN OFICINA_COBRADORA ELSE OFICINA_GESTORA END) || CODIGO_RECIBO || '2'
			        
			        WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			        THEN SUBSTR(PRODUCTO_CONTABLE || SUBSTR(CODIGO_POLIZA,8), 1, 23) || ' ' ||
			             (CASE WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			                   THEN OFICINA_COBRADORA ELSE OFICINA_GESTORA END) || CODIGO_RECIBO 
			        
			        WHEN PERMANENCIA NOT IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			             AND UPPER(TIPO_RECIBO) = :CONST_TIPO_REC_ANUL_K5
			        THEN SUBSTR(PRODUCTO_CONTABLE || SUBSTR(CODIGO_POLIZA,8), 1, 23) || ' ' ||
			             (CASE WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			                   THEN OFICINA_COBRADORA ELSE OFICINA_GESTORA END) || CODIGO_RECIBO || '1'
			        
			        WHEN UPPER(ESTADO_RECIBO) = :CONST_RECIBO_EXTORNO
			        THEN SUBSTR(PRODUCTO_CONTABLE || SUBSTR(CODIGO_POLIZA,8), 1, 23) || ' ' ||
			             (CASE WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			                   THEN OFICINA_COBRADORA ELSE OFICINA_GESTORA END) || CODIGO_RECIBO || '2'
			        
			        ELSE SUBSTR(PRODUCTO_CONTABLE || SUBSTR(CODIGO_POLIZA,8), 1, 23) || ' ' ||
			             (CASE WHEN PERMANENCIA IN (:CONST_RECIBOS_ESPECIFICOS_10, :CONST_RECIBOS_ESPECIFICOS_20)
			                   THEN OFICINA_COBRADORA ELSE OFICINA_GESTORA END) || CODIGO_RECIBO 
			    END AS ORDERID
			    --SUBLINENUMBER
				,TO_NUMBER(SUBSTR (CODIGO_POLIZA, 3, 5)) * 1000 + IFNULL(NUM_ORDEN_MOVIMIENTO,0) AS SUBLINENUMBER
				--LINENUMBER
				,0 AS LINENUMBER,
				ROW_NUMBER() OVER (
					PARTITION BY
						CODIGO_POLIZA, CODIGO_RECIBO, ESTADO_RECIBO, CODIGO_SUPLEMENTO
					ORDER BY FECHA_EFECTO_RECIBO ASC, CODIGO_RECIBO ASC , ESTADO_RECIBO, PRODUCTO_CONTABLE ASC
				) AS ROW_NUMBER_RECIBOS
			FROM EXT.STAGE_RECIBOS TBL
			WHERE TBL.FILE_NAME = :i_file_name
			AND TBL.ESTADO = :CONST_STAGE_STATUS_OK	
		);
		
		v_num_rows = RECORD_COUNT(:TBL_STAGE_0);
		CALL LIB_GLOBAL:WRITE_LOG (v_permisos_log, proc_name, 'TBL_STAGE_0 Creada con los registros OK - Filas: ' || v_num_rows, i_log_count, i_id_proceso, 'info');
		
		--agregar linenumber para evitar subconsultas futuras
		TBL_STAGE = (
			SELECT 
				TBL.IDENTIFICADOR, TBL.FILE_NAME, TBL.ESTADO, TBL.FECHA_MODIFICACION, TBL.RAMO, TBL.CODIGO_POLIZA, TBL.MOTIVO_ALTA, TBL.FECHA_EFECTO_POLIZA, 
				TBL.FECHA_EMISION_POLIZA, TBL.FECHA_CESION_POLIZA, TBL.MOTIVO_BAJA, TBL.FECHA_BAJA, TBL.FECHA_EFECTO_SUPLEMENTO, TBL.FECHA_VENCIMIENTO, 
				TBL.FECHA_REHABILITACION, TBL.FORMA_PAGO, TBL.TIPO_CAMPANIA, TBL.CODIGO_AGENTE_ORIGINAL, TBL.CODIGO_UNICO_AGENTE, TBL.INSPECTOR, TBL.OFICINA_COBRADORA, 
				TBL.OFICINA_GESTORA, TBL.SEGUNDA_RESIDENCIA, TBL.TARIFA, TBL.ZONA, TBL.CLAVE_RIESGO, TBL.CODIGO_SUPLEMENTO, TBL.DISTRITO_COBRO, TBL.MODALIDAD, TBL.DURACION, 
				TBL.IND_COMI_CALCULADA, TBL.IND_POR_CALCULADO, TBL.POR_COMI_CALCULADA, TBL.IMPORTE_COMISION, TBL.CLAUSULA, TBL.AUMENTO_CAPITALES_GAR, TBL.SUSTITUCION_INCENDIOS, 
				TBL.CODIGO_SINIESTRO, TBL.EXCLUIDO_COMISIONES, TBL.TRASPASADA, TBL.INCRE_PRIMA_ANUAL, TBL.DTO_IMPT_SINIESTRALIDAD, TBL.DTO_POR_PRIORITARIO, TBL.RIESGO, TBL.COLECTIVO, 
				TBL.AUTOLIQUIDA, TBL.KILOMETROS, TBL.PRIMER_RECIBO, TBL.CODIGO_RECIBO, TBL.PERMANENCIA, TBL.TIPO_RECIBO, TBL.ESTADO_RECIBO, TBL.FECHA_COBRO, TBL.FECHA_EFECTO_RECIBO, 
				TBL.FECHA_VENCIMIENTO_RECIBO, TBL.TIPO_MOVIMIENTO, TBL.PORC_DESTO_SOBREPC, TBL.VALOR_POLIZA, TBL.MARCA_RECUPERADO, TBL.PRODUCTO_CONTABLE, TBL.FECHA_ALTA_GAR_POL, 
				TBL.FECHA_BAJA_GAR_POL, TBL.PRIMA_NETA_RECIBO, TBL.PRIMA_BRUTA_RECIBO, TBL.RECARGO, TBL.PORCENTAJE_BONIFICACION, TBL.POLIZA_CON_AGENTE, TBL.MOVILIDAD, TBL.PRIMA_UNICA, 
				TBL.NUM_ORDEN_MOVIMIENTO, TBL.FECHA_EMISION_REC, TBL.CARGO_COMPENSACION, TBL.ZONA_EXPLOTACION, TBL.CODIGO_AGENTE_ZONA, TBL.ORDERID, TBL.SUBLINENUMBER,
				(
					SELECT MAX(X.LINENUMBER) 
					FROM EXT.SALESTRANSACTION X
		            WHERE X.ORDERID = TBL.ORDERID
		                AND X.SUBLINENUMBER = TBL.SUBLINENUMBER
		                AND X.EVENTTYPEID = TBL.PERMANENCIA
				) AS LINENUMBER,
				ROW_NUMBER_RECIBOS
			FROM :TBL_STAGE_0 TBL
		);
		
		v_num_rows = RECORD_COUNT(:TBL_STAGE);
		CALL LIB_GLOBAL:WRITE_LOG (v_permisos_log, proc_name, 'TBL_STAGE Creada con los registros OK - Filas: ' || v_num_rows, i_log_count, i_id_proceso, 'info');
		
		------------------------------------- Creamos una tabla de DEBUG.
		--COMENTAR EN PRD
		SELECT COUNT(1) INTO v_existe_tabla FROM SYS.TABLES WHERE TABLE_NAME = 'TBL_STAGE_DEBUG';
		
		IF v_existe_tabla > 0 THEN
			DROP TABLE EXT.TBL_STAGE_DEBUG;
		END IF;
		
		CREATE TABLE EXT.TBL_STAGE_DEBUG AS (SELECT * FROM :TBL_STAGE);
	    CALL LIB_GLOBAL:WRITE_LOG (v_permisos_log, proc_name, 'Creada la tabla temporal TBL_STAGE_DEBUG' , i_log_count, i_id_proceso, 'debug');
		------------------------------------- COMENTAR EN PRD
		
		--mejora rendimiento
