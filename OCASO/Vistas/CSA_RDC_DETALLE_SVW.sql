	"TIPO_INFORME",
	"PERIODO",
	"PERIODO_FORMATO",
	"COD_AGENTE",
	"NOMBRE_AGENTE",
	"NIF",
	"NIF_NOMBRE",
	"TIPO_AGENTE",
	"COD_AGENTE_TABLA",
	"NOMBRE_AGENTE_TABLA",
	"COD_PROD",
	"POLIZA",
	"PRODUCTO",
	"TIPO_REC",
	"FEC_EMISION",
	"FEC_COBRO",
	"POL_FIS",
	"POL_CORR",
	"PRIMA",
	"SOLO_DIFERENCIAS",
	"FEC_ACTUALIZACION",
	"PERIODSEQ",
	"POSITIONSEQ") AS
( 		(SELECT 
			"TIPO_INFORME",
			"PERIODO",
			"PERIODO_FORMATO",
			"COD_AGENTE",
			"NOMBRE_AGENTE",
			"NIF",
