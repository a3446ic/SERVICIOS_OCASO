			NULL,
			NULL,
			NULL,
			'R2' AS QUERY,
			CASE
				WHEN POS_PRIN LIKE '%999999' THEN 'AGENCIAS'
				ELSE 'NORMAL'
			END AS REPORT
		FROM 
			EXT.FINAL_REPEXT_FILE AS FIN
			INNER JOIN
			TCMP.CS_PERIOD AS PER
			ON FIN.PERIODSEQ = PER.PERIODSEQ
				AND PER.REMOVEDATE = TO_DATE( '22000101', 'YYYYMMDD' )
		WHERE TIPO_PAGO IS NOT NULL)) )
WITH READ ONLY;
