CREATE OR REPLACE VIEW "EXT"."CSA_BAL_PEPI_RESUMEN_SVW" ( "POS_PRIN", "COMISION", "TIPO_AGENTE", "REGIONAL", "SUCURSAL", "OFICINA", "POS_CALLIDUS", "AGENTE", "OFI_NIF_NOMBRE", "IMPORTE_ACUMULADO", "FILAS_TABLA", "POL_FIS_MES", "POL_CORR_MES", "PRIMAS_MES", "PRIMAS_CORR_MES", "POL_FIS_ANUAL", "POL_CORR_ANUAL", "PRIMAS_ANUAL", "PRIMAS_CORR_ANUAL", "IMPORTE_MENSUAL", "IMPORTE_ANUAL", "NIF", "PERIODO", "PERIODO_FORMATO", "FECHA_ULT_ACT", "SOLO_DIFERENCIAS", "POSITIONSEQ", "PERIODSEQ" ) AS (SELECT
	 POS_PRIN,
	 COMISION,
	 TIPO_AGENTE,
	 IFNULL(REGIONAL,'-'),
	 IFNULL(SUCURSAL,'-'),
	 CASE WHEN OFICINA LIKE '%SELECCIONAR%' THEN ' ' ELSE IFNULL(OFICINA,'-') END AS OFICINA,
	 POS_CALLIDUS,
	 CASE WHEN OFICINA LIKE '%SELECCIONAR%' THEN ' ' ELSE RIGHT(POS_PRIN,4) ||' - '|| POS_CALLIDUS ||' - '|| NOMBRE END AS AGENTE,
	 CASE WHEN OFICINA LIKE '%SELECCIONAR%' THEN '--SELECCIONAR--' ELSE NIF ||' - '|| NOMBRE END AS OFI_NIF_NOMBRE,
	 IMPORTE_ACUMULADO,
	 FILAS_TABLA,
	 POL_FIS_MES,
	 POL_CORR_MES,
	 PRIMAS_MES,
	 PRIMAS_CORR_MES,
	 POL_FIS_ANUAL,
	 POL_CORR_ANUAL,
	 PRIMAS_ANUAL,
	 PRIMAS_CORR_ANUAL,
	 IMPORTE_MENSUAL,
	 IMPORTE_ANUAL,
	 NIF,
	 PERIODO,
	 PERIODO_FORMATO,
	 FECHA_ULT_ACT,
	 SOLO_DIFERENCIAS,
	 POSITIONSEQ,
	 PERIODSEQ
FROM EXT.OUT_PEPI_RESUMEN_FINAL_REP
WHERE TIPO_CIERRE = 'BAL'
AND PERIODSEQ IN (SELECT PERIODSEQ FROM EXT.LIB_CREAR_TABLAS:N_MESES(13))) WITH  STRUCTURED PRIVILEGE CHECK