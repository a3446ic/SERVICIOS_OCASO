CREATE VIEW "EXT"."CSA_REPARTO_PAGOS_SVW"(
	"COMPANYA",
	"PERIODO",
	"PERIODO_FORMATO",
	"FEC_CARGO",
	"EARNING_CODE",
	"EARNING_GROUP",
	"PROGRAMA",
	"DEPOSITO",
	"TIPO_PAGO",
	"COD_AGENTE",
	"IMPORTE",
	"TIPO_REPARTO",
	"COD_UNICO",
	"NIF",
	"TIPO_AGENTE",
	"MANAGER",
	"ESTADO_REPARTO",
	"POSITIONSEQ",
	"PERIODSEQ") AS
( 		(SELECT 
			"COMPANYA",
			"PERIODO",
			"PERIODO_FORMATO",
			"FEC_CARGO",
			"EARNING_CODE",
			"EARNING_GROUP",
			"PROGRAMA",
			"DEPOSITO",
			"TIPO_PAGO",
			"COD_AGENTE",
			"IMPORTE",
			"TIPO_REPARTO",
			"COD_UNICO",
			"NIF_NOMBRE",
			"TIPO_AGENTE",
			"MANAGER",
			"ESTADO_REPARTO",
			"POSITIONSEQ",
			"PERIODSEQ"
		FROM EXT.OUT_REPARTO_PAGOS_FINAL_REP
		WHERE (PERIODSEQ IN (SELECT PERIODSEQ
			FROM EXT.LIB_CREAR_TABLAS:N_MESES(5)))) );
