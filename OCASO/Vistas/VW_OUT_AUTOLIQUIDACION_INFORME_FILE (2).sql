CREATE VIEW "EXT"."VW_OUT_AUTOLIQUIDACION_INFORME_FILE"("LINE") AS
( 		(SELECT "LINE"
		FROM 
			(
				(SELECT LINE
				FROM EXT.OUT_AUTOLIQUIDACION_INFORME_FILE

				UNION ALL

				SELECT NULL
				FROM DUMMY)
			)
		ORDER BY 
			CASE
				WHEN LINE IS NULL THEN 1
				ELSE 0
			END ASC, 
			LINE ASC) )
WITH READ ONLY;
