CREATE VIEW "EXT"."CSA_PROD_AGENTES_SVW_E" ( "COMPANYA", "ANYO", "PERIODSEQ", "PERIODO", "MES", "PARTICIPANTSEQ", "POSITIONSEQ", "POSITIONNAME", "POSITIONSEQ_PRIN", "POS_PRIN", "ID_TIPO_AGENTE", "TIPO_AGENTE", "COD_REGIONAL", "REGIONAL", "COD_SUCURSAL", "SUCURSAL", "COD_OFICINA", "OFICINA", "NOMBRE", "NIF", "MANAGER_POS_PRIN", "NAME", "ORDEN_AGRUPACIONES_RAMOS", "AGRUPACIONES_RAMOS", "ORDEN_TIPO", "TIPO", "VALUE", "LASTUPDATE" ) AS (SELECT DISTINCT 'ETERNA' COMPANYA
    , INYC_PROD_AGENTES.YEAR ANYO              
    , INYC_PROD_AGENTES.PERIODSEQ
    , INYC_PROD_AGENTES.PERIODO
	, CASE WHEN SUBSTR_BEFORE(INYC_PROD_AGENTES.PERIODO, ' ') = 'Enero' THEN '01 Enero'
		WHEN SUBSTR_BEFORE(INYC_PROD_AGENTES.PERIODO, ' ') = 'Febrero' THEN '02 Febrero'
		WHEN SUBSTR_BEFORE(INYC_PROD_AGENTES.PERIODO, ' ') = 'Marzo' THEN '03 Marzo'
