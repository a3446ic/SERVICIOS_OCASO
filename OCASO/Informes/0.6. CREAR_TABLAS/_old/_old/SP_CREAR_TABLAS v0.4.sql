			CALL EXT.LIB_CREAR_TABLAS:UPDATE_FECHAS_WEBI(i_PeriodSeq, 'TEST_OUT_PERC_AGENTES_REP');

			CALL LIB_GLOBAL:WRITE_LOG (v_permisos_log, proc_name, 'Fin actualización de fecha en OUT_FECHAS_WEBI_REP', i_log_count, i_id_proceso, 'debug');

			-- Revisamos si se debe detener el proceso
			call EXT.LIB_CREAR_TABLAS:w_stop(:v_stop);
