		AND P.REMOVEDATE = TO_DATE('22000101','YYYYMMDD')
	WHERE TIPO_PAGO IS NOT NULL
		AND P.PERIODSEQ = :v_PeriodSeq
	GROUP BY P.PERIODSEQ,
		P.NAME,
