			WHEN SUBSTR_BEFORE(P.NAME, ' ') = 'Abril' THEN ' 04 '
			WHEN SUBSTR_BEFORE(P.NAME, ' ') = 'Mayo' THEN ' 05 '
			WHEN SUBSTR_BEFORE(P.NAME, ' ') = 'Junio' THEN ' 06 '
			WHEN SUBSTR_BEFORE(P.NAME, ' ') = 'Julio' THEN ' 07 '
			WHEN SUBSTR_BEFORE(P.NAME, ' ') = 'Agosto' THEN ' 08 '
