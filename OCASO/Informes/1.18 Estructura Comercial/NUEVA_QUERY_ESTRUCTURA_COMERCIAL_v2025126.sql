    SELECT DISTINCT RULEELEMENTOWNERSEQ
    FROM CS_POSITION pos
    WHERE pos.removeDate = TO_DATE('22000101', 'YYYYMMDD')
      AND pos.effectiveEndDate >= '2020-01-01'
