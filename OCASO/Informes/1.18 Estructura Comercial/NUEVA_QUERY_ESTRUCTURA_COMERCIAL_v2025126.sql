								AND SUC.EPOS_GENERICNUMBER2 IS NULL 
								AND SUC.EPOS_EFFECTIVESTARTDATE < POS.EFFECTIVESTARTDATE and  SUC.EPOS_EFFECTIVEENDDATE >= POS.EFFECTIVESTARTDATE
								AND SUC.EPAR_EFFECTIVESTARTDATE <  POS.EFFECTIVESTARTDATE  and  SUC.EPAR_EFFECTIVEENDDATE >=  POS.EFFECTIVESTARTDATE  
