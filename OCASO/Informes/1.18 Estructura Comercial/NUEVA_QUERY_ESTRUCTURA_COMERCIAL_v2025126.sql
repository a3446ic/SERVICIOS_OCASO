								AND PTO_VENTA.EPOS_GENERICNUMBER2 IS NULL 
								AND PTO_VENTA.EPOS_EFFECTIVESTARTDATE < POS.EFFECTIVESTARTDATE and  PTO_VENTA.EPOS_EFFECTIVEENDDATE >= POS.EFFECTIVESTARTDATE
								AND PTO_VENTA.EPAR_EFFECTIVESTARTDATE <  POS.EFFECTIVESTARTDATE  and  PTO_VENTA.EPAR_EFFECTIVEENDDATE >=  POS.EFFECTIVESTARTDATE  
								AND PTO_VENTA.ETIT_EFFECTIVESTARTDATE <  POS.EFFECTIVESTARTDATE  and  PTO_VENTA.ETIT_EFFECTIVEENDDATE >=  POS.EFFECTIVESTARTDATE
-- OFI
LEFT JOIN ESTRUCTURA OFI ON PTO_VENTA.EPOS_MANAGERSEQ = OFI.EPOSITIONSEQ
								AND OFI.EPOS_GENERICNUMBER2 IS NULL 
								AND OFI.EPOS_EFFECTIVESTARTDATE < POS.EFFECTIVESTARTDATE and  OFI.EPOS_EFFECTIVEENDDATE >= POS.EFFECTIVESTARTDATE
								AND OFI.EPAR_EFFECTIVESTARTDATE <  POS.EFFECTIVESTARTDATE  and  OFI.EPAR_EFFECTIVEENDDATE >=  POS.EFFECTIVESTARTDATE  
								AND OFI.ETIT_EFFECTIVESTARTDATE <  POS.EFFECTIVESTARTDATE  and  OFI.ETIT_EFFECTIVEENDDATE >=  POS.EFFECTIVESTARTDATE


-- SUC
