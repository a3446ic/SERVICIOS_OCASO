	ON  PAR.PAYEESEQ = POS.PAYEESEQ and PAR.REMOVEDATE = TO_DATE('22000101','yyyymmdd')
	AND PAR.EFFECTIVESTARTDATE<= POS.EFFECTIVESTARTDATE and  PAR.EFFECTIVEENDDATE > POS.EFFECTIVESTARTDATE

INNER JOIN TCMP.CS_PAYEE R ON PAR.PAYEESEQ = R.PAYEESEQ and R.REMOVEDATE = TO_DATE('22000101','yyyymmdd')
	AND PAR.EFFECTIVESTARTDATE = R.EFFECTIVESTARTDATE and PAR.EFFECTIVEENDDATE = R.EFFECTIVEENDDATE	

INNER JOIN TCMP.CS_TITLE TIT ON  POS.TITLESEQ = TIT.RULEELEMENTOWNERSEQ  AND TIT.REMOVEDATE = TO_DATE('22000101','yyyymmdd') 
	AND TIT.EFFECTIVESTARTDATE<= POS.EFFECTIVESTARTDATE and  TIT.EFFECTIVEENDDATE > POS.EFFECTIVESTARTDATE
        			
