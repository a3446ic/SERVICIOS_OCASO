PAR.TAXID , -- Tipo de IRPF
POS.EFFECTIVESTARTDATE as POS_EFFECTIVESTARTDATE, -- Fecha Inicio Efectividad
IFNULL(CASE WHEN POS.EFFECTIVEENDDATE = '22000101' THEN ADD_YEARS(POS.EFFECTIVEENDDATE, -100) ELSE ADD_SECONDS(POS.EFFECTIVEENDDATE, -1) END, ' ') as POS_EFFECTIVEENDDATE, -- Fecha Fin Efectividad, restado un segundo o 100 años
IFNULL(RTRIM(PAR.FIRSTNAME) || ' ','')  || IFNULL(RTRIM(PAR.LASTNAME),'') || IFNULL(' ' || RTRIM(PAR.SUFFIX), '') AS NOMBRE_COMPLETO, 
