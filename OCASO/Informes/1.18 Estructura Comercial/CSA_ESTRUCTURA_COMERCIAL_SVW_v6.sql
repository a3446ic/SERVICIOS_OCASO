IFNULL(POS.GENERICATTRIBUTE8,' ') as POSITIONGENERICATTRIBUTE8, -- Compañía (GA8)
POS.GENERICATTRIBUTE13 as POSITIONGENERICATTRIBUTE13, -- Año Captación (GA13)
POS.GENERICATTRIBUTE14 as POSITIONGENERICATTRIBUTE14, -- Inspector Captador (GA14)
POS.GENERICNUMBER1 as POSITIONGENERICNUMBER1, -- ID Tipo Principal Agente (GN1)
POS.GENERICNUMBER2 as POSITIONGENERICNUMBER2, -- ID Tipo Agente (GN2)
POS.GENERICNUMBER3 as POSITIONGENERICNUMBER3, -- ID Clase Oficina (GN3)
POS.GENERICNUMBER4 as POSITIONGENERICNUMBER4, -- ID Tipo Oficina (GN4)
