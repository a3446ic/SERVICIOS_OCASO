            ELSE PTO_VENTA.EPOS_NAME END 
    END || ' - ' ||
    CASE WHEN PTO_VENTA.EPOS_GENERICNUMBER3 IN (5) THEN SUC.LASTNAME
        ELSE CASE WHEN PTO_VENTA.EPOS_GENERICNUMBER3 IN (4,7) THEN OFI.LASTNAME
            ELSE PTO_VENTA.LASTNAME END 
    END , ' ' ) AS SUCURSAL,                                                                                            --titleGenericAttribute2
    IFNULL( CASE WHEN PTO_VENTA.EPOS_GENERICNUMBER3 IN (5) THEN OFI.EPOS_NAME  
        ELSE PTO_VENTA.EPOS_NAME END, ' ') as IDOFICINA,
    IFNULL( CASE WHEN PTO_VENTA.EPOS_GENERICNUMBER3 IN (5) THEN OFI.EPOS_NAME  
        ELSE PTO_VENTA.EPOS_NAME END || ' - ' ||
    CASE WHEN PTO_VENTA.EPOS_GENERICNUMBER3 IN (5) THEN OFI.LASTNAME  
        ELSE PTO_VENTA.LASTNAME END, ' ') AS OFICINA,
IFNULL( LEFT(POS.GENERICATTRIBUTE3, 4), ' ') as PV, IFNULL( RIGHT(Pos.GENERICATTRIBUTE3, 4), ' ' ) as CODIGO,
MANAGER.EPOS_GENERICATTRIBUTE3 as INSPECTOR_NAME, MANAGER.NIF as INSPECTOR_NIF, MANAGER.NOMBRE_COMPLETO as INSPECTOR_NOMBRE_COMPLETO, 
